let current=0, lastWheel=0;
const sections=[...document.querySelectorAll('.slide')];
const nav=[...document.querySelectorAll('.nav-step')];
const tiles=[...document.querySelectorAll('.overview-item')];
function goTo(next,{updateHash=true}={}){
 const target=Math.max(0,Math.min(slides.length-1,next));
 if(target!==current){sections[current].classList.remove('is-active');sections[current].classList.add('exiting'); const old=current;setTimeout(()=>sections[old].classList.remove('exiting'),580);current=target;}
 sections.forEach((s,i)=>{s.classList.toggle('is-active',i===current);s.setAttribute('aria-hidden',i===current?'false':'true');if(i===current)s.scrollTop=0;});
 nav.forEach((b,i)=>{b.classList.toggle('active',i===current);if(i===current)b.setAttribute('aria-current','step');else b.removeAttribute('aria-current')});
 tiles.forEach((b,i)=>b.classList.toggle('selected',i===current));
 $('headerCount').innerHTML=`${String(current+1).padStart(2,'0')} <span>/ ${slides.length}</span>`;
 $('progressFill').style.width=`${(current+1)/slides.length*100}%`;
 $('prevBtn').disabled=current===0;$('nextBtn').disabled=current===slides.length-1;
 $('nextBtn').querySelector('span').textContent=current===slides.length-1?'마지막':'다음';
 document.title=`${slides[current].category} | 천안시 직원 후생복지`;
 if(updateHash&&location.hash!==`#slide-${current+1}`)history.replaceState(null,'',`#slide-${current+1}`);
}
function openOverview(){if(!$('overviewDialog').open)$('overviewDialog').showModal()}
function closeOverview(){if($('overviewDialog').open)$('overviewDialog').close()}
$('prevBtn').addEventListener('click',()=>goTo(current-1));$('nextBtn').addEventListener('click',()=>goTo(current+1));
$('overviewBtn').addEventListener('click',openOverview);$('closeOverview').addEventListener('click',closeOverview);
$('overviewDialog').addEventListener('click',e=>{if(e.target===$('overviewDialog'))closeOverview()});
document.querySelectorAll('[data-slide]').forEach(b=>b.addEventListener('click',()=>{goTo(Number(b.dataset.slide));closeOverview()}));
document.addEventListener('keydown',e=>{if($('overviewDialog').open)return;if(['ArrowRight','ArrowDown','PageDown',' '].includes(e.key)){e.preventDefault();goTo(current+1)}if(['ArrowLeft','ArrowUp','PageUp'].includes(e.key)){e.preventDefault();goTo(current-1)}if(e.key==='Home'){e.preventDefault();goTo(0)}if(e.key==='End'){e.preventDefault();goTo(slides.length-1)}});
$('presentation').addEventListener('wheel',e=>{if(window.matchMedia('(max-width: 700px)').matches)return;if(Math.abs(e.deltaY)<24)return;if(Date.now()-lastWheel<680)return;lastWheel=Date.now();goTo(current+(e.deltaY>0?1:-1))},{passive:true});
let startX=0,startY=0;
$('presentation').addEventListener('touchstart',e=>{startX=e.changedTouches[0].screenX;startY=e.changedTouches[0].screenY},{passive:true});
$('presentation').addEventListener('touchend',e=>{const dx=e.changedTouches[0].screenX-startX,dy=e.changedTouches[0].screenY-startY;if(Math.abs(dx)>55&&Math.abs(dx)>Math.abs(dy)*1.35)goTo(current+(dx<0?1:-1))},{passive:true});
window.addEventListener('hashchange',()=>{const m=location.hash.match(/^#slide-(\d+)$/);if(m)goTo(Number(m[1])-1,{updateHash:false})});
